import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const CONFIG_PATH = path.join(ROOT_DIR, 'data', 'tts-scenes.json');
const PUBLIC_TTS_DIR = path.join(ROOT_DIR, 'public', 'tts');
const MANIFEST_PATH = path.join(PUBLIC_TTS_DIR, 'manifest.json');
const GENERATED_TS_PATH = path.join(ROOT_DIR, 'src', 'data', 'scene-audio.ts');

loadEnvFile(path.join(ROOT_DIR, '.env.local'));

const QWEN_API_URL =
  process.env.QWEN_TTS_API_URL ??
  'https://dashscope.aliyuncs.com/api/v1/services/audio/tts/SpeechSynthesizer';
const MINIMAX_API_URL =
  process.env.MINIMAX_TTS_API_URL ?? 'https://api.minimax.io/v1/t2a_v2';

const args = new Set(process.argv.slice(2));
const force = args.has('--force');
const dryRun = args.has('--dry-run');

const config = JSON.parse(await fs.readFile(CONFIG_PATH, 'utf8'));
const manifest = await readJsonSafe(MANIFEST_PATH, { items: {} });
const nextItems = {};

await fs.mkdir(PUBLIC_TTS_DIR, { recursive: true });

for (const scene of config.scenes ?? []) {
  validateScene(scene);

  const provider = resolveProvider(
    process.env.TTS_PROVIDER ?? scene.provider ?? config.global?.provider ?? 'qwen'
  );
  const text = scene.text.trim();
  if (!text) {
    console.warn(`[skip] scene ${scene.sceneId}: empty text`);
    continue;
  }

  const outputFormat = scene.format ?? config.global?.format ?? 'wav';
  const outputFileName = scene.outputFileName ?? `narration.${outputFormat}`;
  const relPath = path.posix.join('tts', scene.sceneId, outputFileName);
  const absPath = path.join(ROOT_DIR, 'public', relPath);

  const request = buildTtsRequest({ provider, scene, config, text, outputFormat });

  const fingerprint = sha1(
    JSON.stringify({
      provider,
      model: request.model,
      input: request.input,
    })
  );

  const previous = manifest.items?.[scene.sceneId];
  const fileExists = await exists(absPath);

  if (!force && fileExists && previous?.fingerprint === fingerprint) {
    nextItems[scene.sceneId] = previous;
    console.log(`[skip] scene ${scene.sceneId}: unchanged`);
    continue;
  }

  if (dryRun) {
    console.log(`[dry-run] scene ${scene.sceneId} (${provider}): ${text}`);
    continue;
  }

  console.log(`[generate] scene ${scene.sceneId} (${provider})`);
  await fs.mkdir(path.dirname(absPath), { recursive: true });

  const result = await synthesize({
    provider,
    sceneId: scene.sceneId,
    model: request.model,
    input: request.input,
  });
  const audioBuffer = result.audioBuffer;
  await fs.writeFile(absPath, audioBuffer);

  const durationSec =
    outputFormat === 'wav'
      ? getWavDurationSec(audioBuffer) ?? result.durationSec
      : result.durationSec;

  nextItems[scene.sceneId] = {
    sceneId: scene.sceneId,
    provider,
    text,
    src: relPath.replaceAll(path.sep, '/'),
    format: outputFormat,
    model: request.model,
    voice: request.voice,
    requestId: result.requestId,
    durationSec,
    characters: result.characters,
    fingerprint,
    generatedAt: new Date().toISOString(),
  };
}

if (!dryRun) {
  const nextManifest = {
    generatedAt: new Date().toISOString(),
    items: nextItems,
  };

  await fs.writeFile(MANIFEST_PATH, `${JSON.stringify(nextManifest, null, 2)}\n`);
  await fs.writeFile(GENERATED_TS_PATH, buildSceneAudioModule(nextItems));

  const generatedCount = Object.keys(nextItems).length;
  console.log(`Generated scene audio manifest with ${generatedCount} entries.`);
}

function validateScene(scene) {
  if (!scene || typeof scene !== 'object') {
    throw new Error('Each scene entry must be an object.');
  }

  if (typeof scene.sceneId !== 'string' || !scene.sceneId.trim()) {
    throw new Error(`Invalid sceneId: ${JSON.stringify(scene)}`);
  }

  if (typeof scene.text !== 'string') {
    throw new Error(`Scene ${scene.sceneId} is missing a string text field.`);
  }
}

function buildSceneAudioModule(items) {
  const serializable = {};

  for (const [sceneId, item] of Object.entries(items)) {
    serializable[sceneId] = {
      src: item.src,
      durationSec: item.durationSec,
      provider: item.provider,
      requestId: item.requestId,
      model: item.model,
      voice: item.voice,
      text: item.text,
    };
  }

  return `import type { SceneId } from '../types';

export interface SceneAudioMeta {
  src: string;
  durationSec?: number;
  provider: string;
  requestId: string;
  model: string;
  voice: string;
  text: string;
}

// Auto-generated by scripts/generate-qwen-tts.mjs
export const SCENE_AUDIO: Partial<Record<SceneId, SceneAudioMeta>> = ${JSON.stringify(
    serializable,
    null,
    2
  )};
`;
}

function buildTtsRequest({ provider, scene, config, text, outputFormat }) {
  if (provider === 'minimax') {
    const model =
      scene.minimaxModel ??
      config.global?.minimaxModel ??
      process.env.MINIMAX_TTS_MODEL ??
      scene.model ??
      config.global?.model ??
      'speech-2.8-hd';
    const voice =
      scene.minimaxVoice ??
      config.global?.minimaxVoice ??
      process.env.MINIMAX_TTS_VOICE ??
      scene.voice ??
      config.global?.voice ??
      process.env.TTS_VOICE ??
      'male-qn-qingse';
    const speed = toNumber(
      scene.speed ??
        scene.rate ??
        config.global?.speed ??
        config.global?.rate ??
        process.env.MINIMAX_TTS_SPEED ??
        1
    );
    const volume = toNumber(
      scene.minimaxVolume ??
        scene.vol ??
        config.global?.minimaxVolume ??
        config.global?.vol ??
        process.env.MINIMAX_TTS_VOLUME ??
        1
    );
    const pitch = toNumber(
      scene.minimaxPitch ??
        config.global?.minimaxPitch ??
        process.env.MINIMAX_TTS_PITCH ??
        0
    );

    return {
      model,
      voice,
      input: compactObject({
        model,
        text,
        stream: false,
        language_boost:
          scene.languageBoost ??
          config.global?.languageBoost ??
          process.env.MINIMAX_TTS_LANGUAGE_BOOST ??
          'auto',
        output_format: 'hex',
        voice_setting: compactObject({
          voice_id: voice,
          speed,
          vol: volume,
          pitch,
          english_normalization:
            scene.englishNormalization ?? config.global?.englishNormalization,
        }),
        audio_setting: compactObject({
          sample_rate: toNumber(
            scene.sampleRate ??
              config.global?.sampleRate ??
              process.env.MINIMAX_TTS_SAMPLE_RATE ??
              32000
          ),
          bitrate: toNumber(
            scene.bitrate ?? config.global?.bitrate ?? process.env.MINIMAX_TTS_BITRATE ?? 128000
          ),
          format: outputFormat,
          channel: toNumber(
            scene.channel ?? config.global?.channel ?? process.env.MINIMAX_TTS_CHANNEL ?? 1
          ),
        }),
        pronunciation_dict:
          scene.pronunciationDict ?? config.global?.pronunciationDict ?? undefined,
        subtitle_enable: scene.subtitleEnable ?? config.global?.subtitleEnable,
        subtitle_type: scene.subtitleType ?? config.global?.subtitleType,
      }),
    };
  }

  const model =
    scene.qwenModel ??
    config.global?.qwenModel ??
    process.env.QWEN_TTS_MODEL ??
    scene.model ??
    config.global?.model ??
    'cosyvoice-v3.5-plus';
  const voice =
    scene.qwenVoice ??
    config.global?.qwenVoice ??
    process.env.QWEN_TTS_VOICE ??
    scene.voice ??
    config.global?.voice ??
    process.env.TTS_VOICE;

  if (!voice) {
    throw new Error('Missing environment variable: QWEN_TTS_VOICE');
  }

  return {
    model,
    voice,
    input: compactObject({
      text,
      voice,
      format: outputFormat,
      sample_rate: scene.sampleRate ?? config.global?.sampleRate,
      volume: scene.volume ?? config.global?.volume,
      rate: scene.rate ?? config.global?.rate,
      pitch: scene.pitch ?? config.global?.pitch,
      instruction: scene.instruction || config.global?.instruction || undefined,
      language_hints: scene.languageHints ?? config.global?.languageHints ?? undefined,
      enable_ssml: scene.enableSsml ?? config.global?.enableSsml ?? undefined,
    }),
  };
}

async function synthesize(payload) {
  if (payload.provider === 'minimax') {
    return synthesizeMinimax(payload);
  }

  return synthesizeQwen(payload);
}

async function synthesizeQwen(payload) {
  const apiKey = requireEnv('QWEN_TTS_API_KEY');
  const response = await fetchWithRetry(
    QWEN_API_URL,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: payload.model,
        input: payload.input,
      }),
    },
    'TTS request'
  );

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(
      `TTS request failed (${response.status} ${response.statusText}): ${errorText}`
    );
  }

  const json = await response.json();
  const audioUrl = json.output?.audio?.url;

  if (!audioUrl) {
    throw new Error(
      `scene ${payload.sceneId} returned no audio URL: ${JSON.stringify(json)}`
    );
  }

  return {
    audioBuffer: await downloadBuffer(audioUrl),
    requestId: json.request_id,
    characters: json.usage?.characters,
  };
}

async function synthesizeMinimax(payload) {
  const apiKey = normalizeBearerToken(requireAnyEnv(['MINIMAX_TTS_API_KEY', 'MINIMAX_API_KEY']));
  const response = await fetchWithRetry(
    MINIMAX_API_URL,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(payload.input),
    },
    'MiniMax TTS request'
  );

  const responseText = await response.text();
  if (!response.ok) {
    throw new Error(
      `MiniMax TTS request failed (${response.status} ${response.statusText}): ${responseText}`
    );
  }

  const json = JSON.parse(responseText);
  const statusCode = json.base_resp?.status_code;
  if (statusCode != null && statusCode !== 0) {
    throw new Error(
      `MiniMax TTS request failed (${statusCode}): ${
        json.base_resp?.status_msg ?? responseText
      }`
    );
  }

  const audioHex = json.data?.audio ?? json.data?.audio_file;
  if (!audioHex) {
    throw new Error(
      `scene ${payload.sceneId} returned no MiniMax audio data: ${JSON.stringify(json)}`
    );
  }

  return {
    audioBuffer: Buffer.from(audioHex, 'hex'),
    requestId: json.trace_id,
    characters: json.extra_info?.usage_characters,
    durationSec:
      typeof json.extra_info?.audio_length === 'number'
        ? round(json.extra_info.audio_length / 1000)
        : undefined,
  };
}

async function downloadBuffer(url) {
  const response = await fetchWithRetry(url, {}, 'Audio download');
  if (!response.ok) {
    throw new Error(
      `Audio download failed (${response.status} ${response.statusText})`
    );
  }

  return Buffer.from(await response.arrayBuffer());
}

async function fetchWithRetry(url, options, label) {
  const attempts = 3;

  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return await fetch(url, {
        ...options,
        signal: AbortSignal.timeout(90000),
      });
    } catch (error) {
      if (attempt === attempts) {
        const detail =
          error instanceof Error ? error.message : JSON.stringify(error);
        throw new Error(`${label} failed after ${attempts} attempts: ${detail}`);
      }

      console.warn(`[retry] ${label} attempt ${attempt}/${attempts} failed`);
      await wait(attempt * 1500);
    }
  }

  throw new Error(`${label} failed unexpectedly.`);
}

function wait(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

function getWavDurationSec(buffer) {
  if (buffer.toString('ascii', 0, 4) !== 'RIFF') {
    return undefined;
  }

  let offset = 12;
  let sampleRate;
  let byteRate;
  let dataSize;

  while (offset + 8 <= buffer.length) {
    const chunkId = buffer.toString('ascii', offset, offset + 4);
    const chunkSize = buffer.readUInt32LE(offset + 4);
    const chunkDataOffset = offset + 8;

    if (chunkId === 'fmt ') {
      sampleRate = buffer.readUInt32LE(chunkDataOffset + 4);
      byteRate = buffer.readUInt32LE(chunkDataOffset + 8);
    }

    if (chunkId === 'data') {
      dataSize = chunkSize;
      break;
    }

    offset = chunkDataOffset + chunkSize + (chunkSize % 2);
  }

  if (!dataSize) {
    return undefined;
  }

  if (byteRate && byteRate > 0) {
    return round(dataSize / byteRate);
  }

  if (sampleRate && sampleRate > 0) {
    return round(dataSize / sampleRate);
  }

  return undefined;
}

function round(value) {
  return Math.round(value * 1000) / 1000;
}

function compactObject(input) {
  return Object.fromEntries(
    Object.entries(input).filter(([, value]) => value !== undefined && value !== '')
  );
}

function resolveProvider(provider) {
  const normalized = String(provider).trim().toLowerCase();
  if (normalized === 'qwen' || normalized === 'cosyvoice') {
    return 'qwen';
  }
  if (normalized === 'minimax') {
    return 'minimax';
  }
  throw new Error(`Unsupported TTS provider: ${provider}`);
}

function toNumber(value) {
  if (value == null || value === '') {
    return undefined;
  }
  const number = Number(value);
  return Number.isFinite(number) ? number : value;
}

function sha1(value) {
  return createHash('sha1').update(value).digest('hex');
}

function requireEnv(key) {
  const value = process.env[key];
  if (!value) {
    throw new Error(`Missing environment variable: ${key}`);
  }
  return value;
}

function requireAnyEnv(keys) {
  for (const key of keys) {
    if (process.env[key]) {
      return process.env[key];
    }
  }
  throw new Error(`Missing environment variable: ${keys.join(' or ')}`);
}

function normalizeBearerToken(value) {
  return stripMatchingQuotes(String(value).trim()).replace(/^Bearer\s+/i, '');
}

function loadEnvFile(filePath) {
  try {
    const raw = readFileSync(filePath, 'utf8');
    for (const line of raw.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) {
        continue;
      }
      const equalIndex = trimmed.indexOf('=');
      if (equalIndex === -1) {
        continue;
      }
      const key = trimmed.slice(0, equalIndex).trim();
      const value = stripMatchingQuotes(trimmed.slice(equalIndex + 1).trim());
      if (key && process.env[key] == null) {
        process.env[key] = value;
      }
    }
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      return;
    }
    throw error;
  }
}

function stripMatchingQuotes(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

async function readJsonSafe(filePath, fallback) {
  try {
    return JSON.parse(await fs.readFile(filePath, 'utf8'));
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      return fallback;
    }
    throw error;
  }
}

async function exists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}
